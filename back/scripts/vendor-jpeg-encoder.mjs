// Regenerate the Workers-only adapter from the exact pinned jpeg-js source.
import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
const source = await readFile(new URL('../node_modules/jpeg-js/lib/encoder.js', import.meta.url), 'utf8');
const hash = createHash('sha256').update(source).digest('hex');
if (hash !== '00bde8df2517eca556669ab6fc27b414e9ba3fc52a0a71e1e37ec7c5f19c3d34') throw new Error('Unexpected jpeg-js encoder source; review adapter before regenerating');
let adapted = source.slice(0, source.indexOf("if (typeof module !== 'undefined') {"));
adapted = adapted.replace(/var btoa = btoa \|\| function\(buf\) \{[\s\S]*?\n\};/, '');
adapted = adapted.replace('function JPEGEncoder(quality)', 'export function JPEGEncoder(quality)');
adapted = adapted.replace("if (typeof module === 'undefined') return new Uint8Array(byteout);\n      return Buffer.from(byteout);", 'return new Uint8Array(byteout);');
// Unreachable browser data-URL code is not part of the adapter.
adapted = adapted.replace(/\n\s*var jpegDataUri[\s\S]*?return jpegDataUri/, '');
adapted = adapted.split('\n').map(line => line.trimEnd()).join('\n');
await writeFile(new URL('../src/vendor/jpeg-encoder.js', import.meta.url), `// jpeg-js 0.4.4 encoder; upstream SHA256 ${hash}\n// Generated by scripts/vendor-jpeg-encoder.mjs. BSD notice retained below.\n${adapted}`);
